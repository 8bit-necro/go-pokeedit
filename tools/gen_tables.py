#!/usr/bin/env python3
"""Extract PKHeX (GPL-3.0-or-later) data tables into Go source + embeddable data files.

Usage: gen_tables.py <pkhex-source-root> <go-module-root>
Reads only; never executes anything from the PKHeX tree.
"""
import os
import re
import shutil
import sys

SRC = sys.argv[1]
OUT = sys.argv[2]
CORE = os.path.join(SRC, "PKHeX.Core")


def read(path):
    with open(os.path.join(CORE, path), encoding="utf-8-sig") as f:
        return f.read()


def strip_comments(text):
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


def find_block(text, name):
    """Return the raw text of the `[ ... ]` collection expression after `name =>`/`name =`."""
    m = re.search(r"\b" + re.escape(name) + r"\s*(?:=>|=)\s*(?://[^\n]*\s*)*(?:new\s*\w+\[\]\s*)?\[", text)
    if not m:
        raise KeyError(name)
    i = m.end()
    depth = 1
    j = i
    in_char = False
    while depth:
        c = text[j]
        if in_char:
            if c == "\\":
                j += 1
            elif c == "'":
                in_char = False
        else:
            if c == "'":
                in_char = True
            elif c == "[":
                depth += 1
            elif c == "]":
                depth -= 1
        j += 1
    return text[i:j - 1]


CHAR_RE = r"'(?:\\u[0-9A-Fa-f]{4}|\\.|[^'\\])'"
TOKEN_RE = re.compile(CHAR_RE + r"|-?0x[0-9A-Fa-f]+|-?\d+|[A-Za-z_]\w*")


def parse_char(tok):
    body = tok[1:-1]
    if body.startswith("\\u"):
        return ord(chr(int(body[2:], 16)))
    if body.startswith("\\"):
        return ord({"n": "\n", "t": "\t", "'": "'", "\\": "\\", "0": "\0", '"': '"'}[body[1]])
    return ord(body)


def tokens(block):
    return TOKEN_RE.findall(strip_comments(block))


def nums(block):
    out = []
    for t in tokens(block):
        if t.startswith("'"):
            out.append(parse_char(t))
        else:
            out.append(int(t, 16) if '0x' in t.lower() else int(t, 10))
    return out


def ushort_list(path, name):
    return nums(find_block(read(path), name))


# -------------------------------------------------------------- strings
G1_CONSTS = {
    "NUL": 0, "TOT": ord("*"), "LPK": ord("{"), "LMN": ord("}"), "MNY": ord("¥"),
    "LPO": ord("@"), "LKE": ord("#"), "LEA": ord("%"), "DOT": 0x2024, "SPF": 0x3000,
    "SPH": ord(" "), "RET": ord("⏎"), "LAP": ord("’"),
    "LI0": ord("０"), "LI1": ord("１"), "LI2": ord("２"), "LI3": ord("３"), "LI4": ord("４"),
    "LI5": ord("５"), "LI6": ord("６"), "LI7": ord("７"), "LI8": ord("８"), "LI9": ord("９"),
    "LIA": ord("Ａ"), "LIB": ord("Ｂ"),
    "FGM": ord("♂"), "FGF": ord("♀"), "HGM": ord("♂"), "HGF": ord("♀"),
    "Terminator": 0xFF, "NIS": ord("㋥"), "NOS": ord("㋨"),
}


def char_table(path, name, size):
    text = read(path)
    block = find_block(text, name)
    out = []
    for t in tokens(block):
        if t.startswith("'"):
            out.append(parse_char(t))
        elif t in G1_CONSTS:
            out.append(G1_CONSTS[t])
        else:
            raise ValueError("unknown token %r in %s" % (t, name))
    return out


def go_rune_table(name, vals, size, pad):
    vals = list(vals)
    if len(vals) < size:
        vals += [pad] * (size - len(vals))
    assert len(vals) == size, (name, len(vals))
    lines = []
    for i in range(0, size, 16):
        row = ", ".join("0x%04X" % v for v in vals[i:i + 16])
        lines.append("\t" + row + ",")
    return "var %s = [%d]rune{\n%s\n}\n" % (name, size, "\n".join(lines))


def go_bytes(name, vals, typ="byte"):
    lines = []
    for i in range(0, len(vals), 16):
        lines.append("\t" + ", ".join(str(v) for v in vals[i:i + 16]) + ",")
    return "var %s = []%s{\n%s\n}\n" % (name, typ, "\n".join(lines))


def main():
    out = ["// Code generated by gen_tables.py from PKHeX.Core (GPL-3.0-or-later); DO NOT EDIT.", "",
           "package pokeedit", ""]

    # --- character tables
    s1 = "PKM/Strings/StringConverter1.cs"
    s2 = "PKM/Strings/StringConverter2.cs"
    s3 = "PKM/Strings/StringConverter3.cs"
    out.append(go_rune_table("charsG1EN", char_table(s1, "TableEN", 256), 256, 0))
    out.append(go_rune_table("charsG1JP", char_table(s1, "TableJP", 256), 256, 0))
    out.append(go_rune_table("charsG2EN", char_table(s2, "TableEN", 256), 256, 0))
    out.append(go_rune_table("charsG2FR", char_table(s2, "TableFRE", 256), 256, 0))
    out.append(go_rune_table("charsG2IT", char_table(s2, "TableITA", 256), 256, 0))
    try:
        out.append(go_rune_table("charsG2JP", char_table(s2, "TableJP", 256), 256, 0))
    except KeyError:
        out.append("var charsG2JP = charsG1JP\n")
    out.append(go_rune_table("charsG3EN", char_table(s3, "G3_EN", 256), 256, 0xFF))
    out.append(go_rune_table("charsG3JP", char_table(s3, "G3_JP", 256), 256, 0xFF))

    # --- species converters
    sc = read("PKM/Util/Conversion/SpeciesConverter.cs")
    n2i1 = nums(find_block(sc, "Table1NationalToInternal"))
    i2n1 = nums(find_block(sc, "Table1InternalToNational"))
    assert len(n2i1) == 256 and len(i2n1) == 256, (len(n2i1), len(i2n1))
    out.append(go_bytes("species1NationalToInternal", n2i1))
    out.append(go_bytes("species1InternalToNational", i2n1))
    out.append(go_bytes("species3NationalToInternalDelta", nums(find_block(sc, "Table3NationalToInternal")), "int8"))
    out.append(go_bytes("species3InternalToNationalDelta", nums(find_block(sc, "Table3InternalToNational")), "int8"))

    # --- PP tables
    for g in (1, 2, 3):
        out.append(go_bytes("movePP%d" % g, nums(find_block(read("Moves/MoveInfo%d.cs" % g), "PP"))))

    # --- growth tables
    exp = read("PKM/Util/Experience.cs")
    exp_tables = []
    for i in range(6):
        exp_tables.append(nums(find_block(exp, "Growth%d" % i)))
    for i, t in enumerate(exp_tables):
        assert len(t) == 100, (i, len(t))
    out.append("var growthTables = [6][100]uint32{\n" + "\n".join(
        "\t{" + ", ".join(str(v) for v in t) + "}," for t in exp_tables) + "\n}\n")

    # --- gen1 evolution stages / catch-rate held-item bitmap
    out.append(go_bytes("evoStages1", nums(find_block(read("PersonalInfo/Info/PersonalInfo1.cs"), "EvoStages"))))
    out.append(go_bytes("catchRateIsHeldItem", nums(find_block(read("PKM/Util/Conversion/ItemConverter.cs"), "CatchRateIsHeldItem"))))

    # --- item lists
    i1 = ushort_list("Items/ItemStorage1.cs", "General")
    out.append(go_bytes("items1General", i1, "uint16"))
    f2 = "Items/ItemStorage2.cs"
    for n in ("General", "Balls", "KeyGS", "KeyCrystal", "Machine"):
        out.append(go_bytes("items2" + n, ushort_list(f2, n), "uint16"))
    f3 = "Items/ItemStorage3RS.cs"
    for n in ("General", "Key", "Machine", "Berry", "Balls", "Unreleased"):
        out.append(go_bytes("items3RS" + n, ushort_list(f3, n), "uint16"))
    out.append(go_bytes("items3EKey", ushort_list("Items/ItemStorage3E.cs", "Key"), "uint16"))
    out.append(go_bytes("items3FRLGKey", ushort_list("Items/ItemStorage3FRLG.cs", "Key"), "uint16"))

    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, "tables_gen.go"), "w", encoding="utf-8") as f:
        f.write("\n".join(out))

    # --- embedded data files
    data = os.path.join(OUT, "data")
    os.makedirs(data, exist_ok=True)
    res = os.path.join(CORE, "Resources")
    for g in ("rb", "y", "gs", "c", "rs", "e", "fr", "lg"):
        shutil.copy(os.path.join(res, "byte/personal/personal_" + g), os.path.join(data, "personal_" + g))
        shutil.copy(os.path.join(res, "byte/levelup/lvlmove_%s.pkl" % g), os.path.join(data, "lvlmove_%s.pkl" % g))
    for g in ("g1", "g2", "g3"):
        shutil.copy(os.path.join(res, "byte/evolve/evos_%s.pkl" % g), os.path.join(data, "evos_%s.pkl" % g))

    def text_utf8(src, dst):
        raw = open(src, "rb").read()
        if raw[:2] in (b"\xff\xfe", b"\xfe\xff"):
            s = raw.decode("utf-16")
        else:
            s = raw.decode("utf-8-sig")
        s = s.replace("\r\n", "\n").rstrip("\n")
        with open(dst, "w", encoding="utf-8") as f:
            f.write(s + "\n")

    for lang in ("ja", "en", "fr", "it", "de", "es"):
        text_utf8(os.path.join(res, "text/other/%s/text_Species_%s.txt" % (lang, lang)),
                  os.path.join(data, "species_%s.txt" % lang))
    text_utf8(os.path.join(res, "text/other/en/text_Moves_en.txt"), os.path.join(data, "moves_en.txt"))
    text_utf8(os.path.join(res, "text/other/en/text_Natures_en.txt"), os.path.join(data, "natures_en.txt"))
    text_utf8(os.path.join(res, "text/other/en/text_Types_en.txt"), os.path.join(data, "types_en.txt"))
    for g in (1, 2, 3):
        text_utf8(os.path.join(res, "text/items/gen%d/text_ItemsG%d_en.txt" % (g, g)),
                  os.path.join(data, "items_g%d_en.txt" % g))
    print("ok")


main()
